const primeGalleryRoot = document.querySelector("[data-prime-complete-gallery]");

if (primeGalleryRoot) {
  primeGalleryGroups.forEach((group) => {
    const section = document.createElement("section");
    section.className = "project-gallery-group";

    const heading = document.createElement("h3");
    heading.textContent = `${group.title} · ${(group.files?.length || 0) + (group.extras?.length || 0)}`;

    const strip = document.createElement("div");
    strip.className = "project-gallery-strip";
    strip.setAttribute("aria-label", `${group.title} images for the Prime humanoid robot`);

    const sources = [
      ...(group.files || []).map((file) => `${group.base}${file}`),
      ...(group.extras || []),
    ];

    sources.forEach((src, index) => {
      const link = document.createElement("a");
      link.className = "project-gallery-item";
      link.href = src;
      link.target = "_blank";
      link.rel = "noopener noreferrer";

      const img = document.createElement("img");
      img.src = src;
      img.alt = `${group.title} for the Prime humanoid robot, image ${index + 1}`;
      img.loading = "lazy";
      img.decoding = "async";

      const caption = document.createElement("span");
      caption.textContent = `${group.title} ${index + 1} · open original ↗`;

      link.append(img, caption);
      strip.append(link);
    });

    section.append(heading, strip);
    primeGalleryRoot.append(section);
  });
}
